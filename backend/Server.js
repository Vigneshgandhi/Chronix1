async function decideAdminReport(report, status, adminId, reason = "") {
  const isAccepted = status === "accepted";
  let message = null;
  if (isAccepted && report.chatId && report.messageId) {
    const messages = await messageStore.getMessages(report.chatId);
    message = messages.find((item) => String(item.id) === String(report.messageId) || String(item.id) === `${report.messageId}-sent`);
    if (message) {
      const messageIds = messages.filter((item) => String(item.id) === String(message.id) || String(item.id) === `${message.id}-sent` || String(item.id) === String(report.messageId) || String(item.id) === `${report.messageId}-sent`).map((item) => item.id);
      await messageStore.removeMessages(report.chatId, [...new Set(messageIds)]);
      const payload = { chatId: String(report.chatId), messageId: String(report.messageId), contentType: report.contentType || "message", reason: reason || "Removed after manual Chronix review", timestamp: Date.now(), dissolveAfterMs: 8000 };
      const participantIds = new Set([report.reporterDeviceId, report.reportedDeviceId].filter(Boolean));
      participantIds.forEach((participantId) => io.to(`device:${participantId}`).emit("moderation:content-removed", payload));
      io.to(`chat:${report.chatId}`).emit("moderation:content-removed", payload);
    }
  }
  const updated = moderationStore.updateRecord("reports", report.id, { status, moderationStatus: status, adminId, adminReason: reason, decisionAt: Date.now(), contentState: isAccepted ? "removed" : "active" });
  moderationStore.createRecord("audit", { adminId, action: isAccepted ? "accept_report" : "reject_report", reportId: report.id, targetDeviceId: report.reportedDeviceId, timestamp: Date.now(), reason });
  if (!isAccepted && report.reporterDeviceId) io.to(`device:${report.reporterDeviceId}`).emit("moderation:updated", { reportId: report.id, status, timestamp: Date.now() });
  return { updated, message };
}

