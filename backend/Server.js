app.post("/api/admin/reports/:reportId/analyze", requireAdmin, async (req, res, next) => {
  try {
    const report = moderationStore.getRecord("reports", req.params.reportId);
    if (!report) return res.status(404).json({ success: false, error: "Report not found." });
    if (!report.chatId || !report.messageId) return res.status(400).json({ success: false, error: "This report has no message content to analyze." });
    const messages = await messageStore.getMessages(report.chatId);
    const message = messages.find((item) => String(item.id) === String(report.messageId) || String(item.id) === `${report.messageId}-sent`);
    if (!message) return res.status(410).json({ success: false, error: "Reported content is no longer available for AI review." });
    const analysis = await analyzeReport({ content: message.text || "[Attachment]", category: report.reportCategory, reason: report.reportReason || report.reason });
    const aiResult = analysis.status === "analysis_available" ? { aiDecision: analysis.isViolation ? "violation" : "no_violation", confidence: analysis.confidence, category: analysis.category, explanation: analysis.reason, analyzedAt: Date.now() } : { aiDecision: "unavailable", errorCode: analysis.code, explanation: analysis.message, analyzedAt: Date.now() };
    const updated = moderationStore.updateRecord("reports", report.id, { aiResult, analysisStatus: analysis.status === "analysis_available" && !analysis.isViolation ? "not_violation" : "manual_review" });
    res.json({ success: true, report: updated, analysis });
  } catch (error) { next(error); }
});

