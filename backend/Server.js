app.get("/api/security/:deviceId", (req, res) => {
  const deviceId = String(req.params.deviceId || "");
  if (!hasDeviceId(deviceId)) return res.status(404).json({ success: false, error: "Device not found." });
  const record = securityStore.get(deviceId);
  res.json({ success: true, configured: Boolean(record), publicKey: record?.publicKey || null, encryptionVersion: record?.encryptionVersion || 1 });
});

app.post("/api/security/setup", (req, res) => {
  const { deviceId, publicKey, passwordSalt, passwordVerifier, encryptionVersion } = req.body || {};
  if (typeof deviceId !== "string" || !hasDeviceId(deviceId) || !publicKey || typeof passwordSalt !== "string" || typeof passwordVerifier !== "string") {
    return res.status(400).json({ success: false, error: "Valid device security material is required." });
  }
  if (!securityStore.create(deviceId, { publicKey, passwordSalt, passwordVerifier, encryptionVersion })) {
    return res.status(409).json({ success: false, error: "Security setup already exists for this device." });
  }
  res.status(201).json({ success: true, encryptionVersion: encryptionVersion || 1 });
});

