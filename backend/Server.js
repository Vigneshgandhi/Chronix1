function createFileAccessToken(fileName) {
  const expiresAt = Date.now() + 24 * 60 * 60 * 1000;
  const value = `${fileName}.${expiresAt}`;
  const signature = crypto.createHmac("sha256", process.env.MESSAGE_ENCRYPTION_KEY).update(value).digest("hex");
  return `${expiresAt}.${signature}`;
}

function validFileAccessToken(fileName, token) {
  const [expiresAtValue, signature] = String(token || "").split(".");
  const expiresAt = Number(expiresAtValue);
  if (!Number.isSafeInteger(expiresAt) || expiresAt < Date.now() || !/^[a-f0-9]{64}$/i.test(signature || "")) return false;
  const value = `${fileName}.${expiresAt}`;
  const expected = crypto.createHmac("sha256", process.env.MESSAGE_ENCRYPTION_KEY).update(value).digest("hex");
  return crypto.timingSafeEqual(Buffer.from(signature, "hex"), Buffer.from(expected, "hex"));
}

