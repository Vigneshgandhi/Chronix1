// deviceId -> explicitly connected device IDs. Presence is shared only within
// these pairs, never with every socket on the server.
function getConnectedDeviceIds(deviceId) {
  return new Set(getPersistedConnections(deviceId));
}

function emitToConnectedDevices(deviceId, event, payload) {
  for (const connectedDeviceId of getConnectedDeviceIds(deviceId)) {
    io.to(`device:${connectedDeviceId}`).emit(event, payload);
  }
}

function communicationAllowed(sourceDeviceId, targetDeviceId) {
  return !moderationStore.isBlocked(sourceDeviceId, targetDeviceId) && !moderationStore.isBlocked(targetDeviceId, sourceDeviceId);
}

io.use((socket, next) => {
  const { deviceId, profile, publicKey } = socket.handshake.auth || {};

  if (typeof deviceId !== "string" || deviceId.length < 16 || deviceId.length > 128) {
    return next(new Error("A valid device ID is required"));
  }

  try {
    if (!hasDeviceId(deviceId)) {
      const error = new Error("Device ID must be generated by the server");
      error.data = { code: "UNKNOWN_DEVICE_ID" };
      return next(error);
    }
  } catch (error) {
    return next(error);
  }

  const security = securityStore.get(deviceId);
  if (!security || JSON.stringify(security.publicKey) !== JSON.stringify(publicKey)) {
    return next(new Error("Security setup is required for this device."));
  }

  socket.data.deviceId = deviceId;
  socket.data.initialProfile = profile;
  next();
});

