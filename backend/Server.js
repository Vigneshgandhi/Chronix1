const PORT = Number(process.env.PORT) || 5001;
const HOST = process.env.HOST || "0.0.0.0";

server.on("error", (error) => {
  if (error.code === "EADDRINUSE") {
    console.error(`[Chronix] Port ${PORT} is already in use. Stop the existing server or choose another PORT in backend/.env.`);
    // Report the conflict as a failure. Returning success makes process
    // managers/watchers repeatedly relaunch a server that cannot bind.
    process.exitCode = 1;
    return;
  }

  console.error("[Chronix] Server failed to start:", error.message);
  process.exit(1);
});

server.listen(PORT, HOST, () => {
  console.log(`
    =====================================
    🚀 Chronix Server Started
    =====================================

    URL:
    http://localhost:${PORT}

    Environment:
    ${process.env.NODE_ENV || "development"}

    =====================================
`);
});
