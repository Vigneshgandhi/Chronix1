// Admin access requires both configured credentials and a manually supplied
// verification code. Sessions are intentionally short-lived and in memory.
app.post("/api/admin/login", (req, res) => {
  const { username, password, verificationCode } = req.body || {};
  if (!adminSecretMatches(username, ADMIN_USERNAME) || !adminSecretMatches(password, ADMIN_PASSWORD)) {
    return res.status(401).json({ success: false, error: "Invalid admin credentials." });
  }
  if (!adminSecretMatches(verificationCode, ADMIN_VERIFICATION_CODE)) {
    return res.status(403).json({ success: false, error: "Manual verification failed." });
  }
  const token = crypto.randomBytes(32).toString("hex");
  adminSessions.set(token, { adminId: ADMIN_USERNAME, expiresAt: Date.now() + 8 * 60 * 60 * 1000 });
  return res.json({ success: true, token, expiresIn: 8 * 60 * 60 });
});

